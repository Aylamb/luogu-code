/**
 * 洛谷 P4017 最大食物链计数
 *
 * 题意：
 *   有 n 种生物、m 条“a 吃 b”的捕食关系，求从生产者（不被任何生物吃）
 *   到最高消费者（不吃任何生物）的完整食物链条数，答案对 80112002 取模。
 *
 * 建模：
 *   把每种生物看成点，把捕食关系 a 吃 b 建成有向边 a -> b。
 *   - 入度为 0：没有别的生物吃它 = 生产者 = 食物链的起点
 *   - 出度为 0：它不吃任何生物 = 最高消费者 = 食物链的终点
 *   于是题目等价于：从所有入度为 0 的点出发，走到所有出度为 0 的点，
 *   统计路径总条数。
 *
 * 算法：
 *   记忆化 DFS。dp[u] = 从 u 出发、沿捕食方向走，能形成多少条到终点（出度 0）的链。
 *   转移：
 *     - 出度为 0 时 dp[u] = 1（它本身就是一条完整链的终点）
 *     - 否则 dp[u] = sum(dp[v])，对 u 的所有后继 v 求和，取模
 *   答案 = sum(dp[u])，对所有入度为 0 的 u 求和，取模。
 *
 * 复杂度：O(n + m)。每个点只被首次进入时真正展开一次，每条边只遍历一次。
 */
#include <iostream>
#include <vector>
using namespace std;

int n, m;
vector<int> v[500005];          // 邻接表：v[u] 存 u 的所有后继（即 u 吃谁）
const int MOD = 80112002;       // 题目指定模数
int in[500005];                 // in[u]: 节点 u 的入度（即有多少生物吃 u）
int dp[500005];                 // dp[u]: 从 u 出发的完整食物链条数（记忆化结果）

/**
 * 记忆化 DFS：统计从节点 u 出发能形成的食物链条数。
 *
 * @param u 当前遍历到的生物编号
 * @return  从 u 沿捕食方向走到出度为 0 的节点为止，一共有多少条链（已取模）
 *
 * 说明：
 *   - dfs 的返回值恒 ≥ 1（叶子返回 1，非叶子至少累加一个后继的 ≥1 值），
 *     所以可以用 dp[u] == 0 来判断“该点尚未被计算过”，不会和真实值 0 冲突。
 *   - 记忆化后每个点只会真正展开一次，避免在 DAG 中重复搜索导致指数级复杂度。
 */
int dfs(int u){
    // 已经算过就直接返回（记忆化，避免重复搜索）
    if(dp[u])  return dp[u];

    // 出度为 0：u 不吃任何生物，它就是一条完整食物链的终点，
    // 从 u 出发的链数只有它自己这一条，返回 1。
    if(v[u].empty())  return dp[u] = 1;

    // 一般情况：u 的每个后继都会延伸出一组独立的子链，
    // 把所有后继的 dp 值累加，就得到从 u 出发的总链数；
    // 每加一次立即取模，防止中间结果溢出 int。
    for(int i : v[u])  dp[u] = (dp[u] + dfs(i)) % MOD;
    return dp[u];
}

int main(){
    // 读入生物种类数 n 和捕食关系条数 m
    cin >> n >> m;

    // 建图：a 吃 b，则连有向边 a -> b
    for(int i = 0; i < m; i++){
        int a, b;
        cin >> a >> b;
        v[a].push_back(b);   // a 的后继是 b（a 吃 b）
        in[b]++;             // b 被吃，入度 +1
    }

    // 从所有生产者（入度为 0，没有任何生物吃它）出发，
    // 把它们各自的链数累加起来，就是答案。
    int ans = 0;
    for(int i = 1; i <= n; i++)
        if(in[i] == 0) ans = (ans + dfs(i)) % MOD;

    cout << ans;
    return 0;
}
